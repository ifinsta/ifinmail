"""Registries the domain apps fill in at start-up: capabilities, adapter targets, setting types.

Two layers keep plugins independent of the software that runs the mail:

* A **capability** is the public contract plugins write to (``mail.journal``,
  ``sending.rate_limit``): what the administrator wants, in plain units, never the name of a
  program or one of its settings.
* An **adapter target** is where an engine reads its values (a runtime file applied by a watcher
  in the container that owns the software). Each capability field is bound to one target key,
  with an optional translation of the value.

Swapping an engine means registering new targets and re-binding the fields; manifests do not
change. Core stays neutral: it defines the contracts here and never imports the apps that
implement them. Domain apps register in ``AppConfig.ready()``; registering the same key twice
replaces the entry (Django may call ``ready()`` again in tests and autoreload).
"""

from __future__ import annotations

import hashlib
import os
import time
from collections.abc import Callable, Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path

from backend.apps.core.platform.services.runtime import read_runtime_file, write_runtime_file
from backend.apps.core.plugins.types import ApplyStatus

# A value validator returns an error message, or None when the value is acceptable.
ValueValidator = Callable[[str], str | None]
# A live setting check (e.g. "is this an existing mailbox?") returns an error message or None.
LiveCheck = Callable[[str], str | None]

APPLY_GRACE_SECONDS = 60


def _check_value(spec: TargetKey | CapabilityField | None, where: str, key: str, value: str):
    if spec is None:
        return f'"{key}" is not a value plugins may set at {where}'
    if value == '':
        return None  # empty = remove the setting
    if any(ch in value for ch in '\r\n\0'):
        return 'line breaks are not allowed'
    return spec.validator(value)


def _normalized(spec: TargetKey | CapabilityField | None, value: str) -> str:
    if spec is None or spec.normalize is None or any(ch in value for ch in '\r\n\0'):
        return value
    return spec.normalize(value)


# ------------------------------------------------------------------------------ adapter targets


@dataclass(frozen=True)
class TargetKey:
    validator: ValueValidator
    description: str
    # Optional canonical form (e.g. "EXE, .js" -> "exe,js") applied before validation.
    normalize: Callable[[str], str] | None = None


class AdapterTarget:
    """Where an engine reads plugin values. Subclasses set the class attributes.

    The default implementation renders ``key = value`` lines for every allowed key (empty value =
    remove the setting) into a runtime file, and reads an acknowledgement file holding the SHA-256
    of what the consumer last applied.
    """

    key: str = ''
    # The container that applies it, named in status messages for the administrator.
    service: str = ''
    # Consumed inside the console itself: no runtime file (so secrets never reach the shared
    # runtime volume), always applied. Its values are read with InstallationService.
    in_process: bool = False
    keys: dict[str, TargetKey] = {}
    runtime_file: str = ''
    ack_file: str = ''

    def normalize(self, key: str, value: str) -> str:
        return _normalized(self.keys.get(key), value)

    def validate(self, key: str, value: str) -> str | None:
        return _check_value(self.keys.get(key), self.key, key, value)

    def render(self, values: dict[str, str]) -> str:
        lines = [f'# Generated by ifinmail from enabled plugins ({self.key}). Do not edit.']
        lines += [f'{key} = {values.get(key, "")}' for key in sorted(self.keys)]
        return '\n'.join(lines) + '\n'

    def publish(self, text: str) -> bool:
        """Write the file only when its content changes. Returns whether it was written."""
        if self.in_process:
            return False
        if read_runtime_file(self.runtime_file) == text:
            return False
        write_runtime_file(self.runtime_file, text)
        return True

    def applied_status(self) -> ApplyStatus:
        if self.in_process:
            return ApplyStatus.APPLIED
        current = read_runtime_file(self.runtime_file)
        if current is None:
            return ApplyStatus.UNKNOWN
        ack_dir = Path(os.environ.get('IFINMAIL_STATUS_DIR', '/var/lib/ifinmail/status'))
        try:
            acked = (ack_dir / self.ack_file).read_text(encoding='utf-8').strip()
        except OSError:
            return ApplyStatus.UNKNOWN
        if acked == hashlib.sha256(current.encode('utf-8')).hexdigest():
            return ApplyStatus.APPLIED
        try:
            from backend.apps.core.platform.services.runtime import runtime_dir

            age = time.time() - (runtime_dir() / self.runtime_file).stat().st_mtime
        except OSError:
            return ApplyStatus.UNKNOWN
        return ApplyStatus.APPLYING if age < APPLY_GRACE_SECONDS else ApplyStatus.NOT_APPLIED


# ------------------------------------------------------------------------------ capabilities


@dataclass(frozen=True)
class CapabilityField:
    """One value of the public contract, bound to the adapter target key that carries it."""

    validator: ValueValidator
    description: str
    target: tuple[str, str]  # (adapter target key, key within it)
    normalize: Callable[[str], str] | None = None
    # Contract value -> engine value (e.g. "yes" -> "on"); None passes it through. Empty stays
    # empty (the setting is removed).
    translate: Callable[[str], str] | None = None
    # Carries a ``secret`` setting (stored encrypted); may only be bound to an in-process target.
    secret: bool = False


class Capability:
    """A named, engine-neutral thing plugins can ask for. Subclasses set the class attributes."""

    key: str = ''
    title: str = ''
    description: str = ''
    fields: dict[str, CapabilityField] = {}

    def normalize(self, field: str, value: str) -> str:
        return _normalized(self.fields.get(field), value)

    def validate(self, field: str, value: str) -> str | None:
        return _check_value(self.fields.get(field), self.key, field, value)


_targets: dict[str, AdapterTarget] = {}
_capabilities: dict[str, Capability] = {}
_setting_types: dict[str, tuple[str, LiveCheck]] = {}


def register_target(target: AdapterTarget) -> None:
    if not target.key or not target.keys or not (target.runtime_file or target.in_process):
        raise ValueError('an adapter target needs a key, allowed keys and a runtime file')
    _targets[target.key] = target


def get_target(key: str) -> AdapterTarget | None:
    return _targets.get(key)


def targets() -> list[AdapterTarget]:
    return [_targets[k] for k in sorted(_targets)]


def register_capability(capability: Capability) -> None:
    """Register a capability; every field must be bound to a distinct, existing target key."""
    if not capability.key or not capability.fields:
        raise ValueError('a capability needs a key and at least one field')
    bound = {
        spec.target: (key, name)
        for key, cap in _capabilities.items()
        if key != capability.key
        for name, spec in cap.fields.items()
    }
    for name, spec in capability.fields.items():
        target = _targets.get(spec.target[0])
        if target is None or spec.target[1] not in target.keys:
            raise ValueError(f'{capability.key}.{name} is bound to unknown target {spec.target}')
        if spec.secret and not target.in_process:
            raise ValueError(f'{capability.key}.{name} is secret but its target writes a file')
        if spec.target in bound:
            raise ValueError(f'{capability.key}.{name} and {bound[spec.target]} share a target')
    _capabilities[capability.key] = capability


def get_capability(key: str) -> Capability | None:
    return _capabilities.get(key)


def capabilities() -> list[Capability]:
    return [_capabilities[k] for k in sorted(_capabilities)]


def to_targets(values: Mapping[str, Mapping[str, str]]) -> dict[str, dict[str, str]]:
    """``{capability: {field: value}}`` -> ``{target: {key: value}}``, validated by the target.

    Raises ``ValueError`` when a value cannot be carried (a binding bug, never user input: the
    capability has validated it already).
    """
    out: dict[str, dict[str, str]] = {}
    for cap_key, fields in values.items():
        capability = _capabilities.get(cap_key)
        if capability is None:
            raise ValueError(f'capability {cap_key} is not offered by this server')
        for name, value in fields.items():
            spec = capability.fields[name]
            target_key, key = spec.target
            engine_value = spec.translate(value) if spec.translate and value else value
            target = _targets[target_key]
            error = target.validate(key, target.normalize(key, engine_value))
            if error:
                raise ValueError(f'{cap_key}.{name}: {error}')
            out.setdefault(target_key, {})[key] = engine_value
    return out


def targets_of(capability_keys: Iterable[str]) -> list[AdapterTarget]:
    """The adapter targets the given capabilities write to (for apply status)."""
    keys = {
        spec.target[0]
        for cap_key in capability_keys
        if (cap := _capabilities.get(cap_key)) is not None
        for spec in cap.fields.values()
    }
    return [_targets[k] for k in sorted(keys)]


# ----------------------------------------------------------------------- dynamic sources

# Values that come from live system state rather than from a plugin's settings (for example the
# mailboxes whose sending is paused). They are merged into adapter targets when files are
# rendered, so the same watchers apply them; plugins cannot set or see them.
DynamicSource = Callable[[], Mapping[str, Mapping[str, str]]]
_dynamic_sources: dict[str, DynamicSource] = {}


def register_dynamic_source(name: str, source: DynamicSource) -> None:
    _dynamic_sources[name] = source


def dynamic_values() -> dict[str, dict[str, str]]:
    """``{target: {key: value}}`` from every dynamic source; invalid values are dropped."""
    import logging

    logger = logging.getLogger('backend')
    merged: dict[str, dict[str, str]] = {}
    for name, source in sorted(_dynamic_sources.items()):
        try:
            produced = source()
        except Exception:  # a broken source must not stop the files being written
            logger.exception('Dynamic plugin source %s failed', name)
            continue
        for target_key, pairs in produced.items():
            target = _targets.get(target_key)
            if target is None:
                continue
            for key, value in pairs.items():
                error = target.validate(key, target.normalize(key, value))
                if error:
                    logger.warning('Dynamic source %s: %s.%s %s', name, target_key, key, error)
                    continue
                merged.setdefault(target_key, {})[key] = target.normalize(key, value)
    return merged


def register_setting_type(name: str, base: str, live_check: LiveCheck) -> None:
    """Add a setting type that refines a built-in one (``base``) with a live check."""
    _setting_types[name] = (base, live_check)


def setting_type(name: str) -> tuple[str, LiveCheck] | None:
    return _setting_types.get(name)
