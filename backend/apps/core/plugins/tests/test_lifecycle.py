JOURNAL = 'compliance-journal'
ADDR = 'journal@ifinmail.test'


class _Base(MailTablesTestCase):
    def setUp(self) -> None:
        super().setUp()
        self.status_dir = os.path.join(self.tmp, 'status')
        os.makedirs(self.status_dir)
        patcher = patch.dict(os.environ, {'IFINMAIL_STATUS_DIR': self.status_dir})
        patcher.start()
        self.addCleanup(patcher.stop)
        self.domain = self.make_domain()
        for local in ('journal', 'other'):
            Mailbox.objects.create(domain=self.domain, local_part=local)
        self.point = registry.get_target('postfix.main')

    def file(self) -> str:
        path = Path(self.runtime_dir) / 'postfix-plugins.conf'
        return path.read_text() if path.exists() else ''

    def bcc(self) -> str | None:
        for line in self.file().splitlines():
            if line.startswith('always_bcc ='):
                return line.partition('=')[2].strip()
        return None

    def install(self, address: str = ADDR):
        return InstallationService.install(
            JOURNAL, {'archive_address': address}, 'admin@ifinmail.test'
        )

    def row(self) -> PluginInstallation | None:
        return PluginInstallation.objects.filter(plugin_id=JOURNAL).first()

    def publish_submission(self, **changes: object) -> str:
        sub = SubmissionService.submit(text(**changes), 'dev@ifinmail.test')
        SubmissionService.approve(str(sub.id), 'admin@ifinmail.test')
        return str(sub.id)


class HappyPathTests(_Base):
    def test_install_writes_the_value_and_records_who_and_what(self) -> None:
        result = self.install()
        self.assertEqual((result.from_state, result.to_state), (ABSENT, InstallationState.ENABLED))
        row = self.row()
        self.assertEqual(row.state, InstallationState.ENABLED)
        self.assertEqual((row.target_state, row.pending_operation, row.last_error), ('', '', ''))
        self.assertEqual(row.settings, {'archive_address': ADDR})
        self.assertEqual(row.installed_by, 'admin@ifinmail.test')
        self.assertEqual(self.bcc(), ADDR)
        self.assertTrue(self.file().startswith('# Generated by ifinmail'))
        self.assertTrue(AuditService.has('plugin_install'))

    def test_configure_disable_enable_uninstall_and_reinstall(self) -> None:
        self.install()
        InstallationService.configure(JOURNAL, {'archive_address': 'other@ifinmail.test'}, 'a')
        self.assertEqual(self.bcc(), 'other@ifinmail.test')
        InstallationService.disable(JOURNAL, 'a')
        self.assertEqual(self.row().state, InstallationState.DISABLED)
        self.assertEqual(self.bcc(), '')  # empty = Postfix default restored
        InstallationService.configure(JOURNAL, {'archive_address': ADDR}, 'a')
        self.assertEqual(self.bcc(), '')  # still disabled: nothing written
        InstallationService.enable(JOURNAL, 'a')
        self.assertEqual(self.bcc(), ADDR)
        InstallationService.uninstall(JOURNAL, 'a')
        self.assertIsNone(self.row())
        self.assertEqual(self.bcc(), '')
        self.install()
        self.assertEqual(self.bcc(), ADDR)
        for action in ('configure', 'disable', 'enable', 'uninstall'):
            self.assertTrue(AuditService.has(f'plugin_{action}'), action)

    def test_saving_identical_settings_changes_nothing(self) -> None:
        self.install()
        before = self.row().revision
        result = InstallationService.configure(JOURNAL, {'archive_address': ADDR.upper()}, 'a')
        self.assertEqual(result.from_state, result.to_state)
        self.assertEqual(self.row().revision, before)

    def test_files_are_only_rewritten_when_their_content_changes(self) -> None:
        self.install()
        written = InstallationService.publish_all()
        self.assertEqual(set(written), {p.key for p in registry.targets()})
        self.assertFalse(any(written.values()))
        os.remove(Path(self.runtime_dir) / 'postfix-plugins.conf')
        result = InstallationService.reconcile()
        self.assertTrue(result['written']['postfix.main'])
        self.assertFalse(result['written']['rspamd.policy'])
        self.assertEqual(self.bcc(), ADDR)


class RefusalTests(_Base):
    def test_validation_errors_change_no_state(self) -> None:
        with self.assertRaises(SettingsError) as caught:
            self.install('nobody@ifinmail.test')
        self.assertIn('not a mailbox', caught.exception.errors['archive_address'])
        with self.assertRaises(SettingsError):
            InstallationService.install(JOURNAL, {}, 'a')
        with self.assertRaises(SettingsError):
            self.install('x@ifinmail.test\nrelayhost = evil')
        self.assertIsNone(self.row())
        self.assertEqual(self.file(), '')

    def test_unknown_plugin_double_install_and_not_installed(self) -> None:
        with self.assertRaises(NotFoundError):
            InstallationService.install('no-such-plugin', {}, 'a')
        self.install()
        with self.assertRaises(TransitionError):
            self.install()
        InstallationService.uninstall(JOURNAL, 'a')
        for op in (
            InstallationService.enable,
            InstallationService.disable,
            InstallationService.uninstall,
        ):
            with self.assertRaises(NotFoundError):
                op(JOURNAL, 'a')

    def test_stale_revision_is_refused(self) -> None:
        self.install()
        revision = self.row().revision
        InstallationService.disable(JOURNAL, 'a', revision)
        with self.assertRaises(StaleRevisionError):
            InstallationService.enable(JOURNAL, 'a', revision)  # page loaded before the disable
        InstallationService.enable(JOURNAL, 'a', self.row().revision)

    def test_enable_refuses_settings_that_went_stale(self) -> None:
        self.install()
        InstallationService.disable(JOURNAL, 'a')
        Mailbox.objects.filter(local_part='journal').delete()
        with self.assertRaises(SettingsError):
            InstallationService.enable(JOURNAL, 'a')
        self.assertEqual(self.row().state, InstallationState.DISABLED)

    def test_incompatible_core_is_refused_and_development_builds_are_not(self) -> None:
        with (
            patch.dict(os.environ, {'APP_VERSION': 'v0.0.9'}),
            self.assertRaisesMessage(PluginError, 'needs ifinmail 0.0.10'),
        ):
            self.install()
        self.assertIsNone(self.row())
        with patch.dict(os.environ, {'APP_VERSION': 'v0.0.10-2-gabc1234'}):
            self.install()
        InstallationService.uninstall(JOURNAL, 'a')
        with patch.dict(os.environ, {'APP_VERSION': 'dev'}):
            self.install()

    def test_busy_while_another_operation_runs(self) -> None:
        self.install()
        PluginInstallation.objects.filter(plugin_id=JOURNAL).update(
            state=InstallationState.APPLYING, target_state=InstallationState.DISABLED
        )
        with self.assertRaises(BusyError):
            InstallationService.enable(JOURNAL, 'a')


class TransitionTableTests(_Base):
    """Every operation from every state: allowed exactly when the table says so."""

    def test_the_table_is_enforced_for_every_state_and_operation(self) -> None:
        calls = {
            Operation.ENABLE: lambda: InstallationService.enable(JOURNAL, 'a'),
            Operation.DISABLE: lambda: InstallationService.disable(JOURNAL, 'a'),
            Operation.CONFIGURE: lambda: InstallationService.configure(
                JOURNAL, {'archive_address': 'other@ifinmail.test'}, 'a'
            ),
            Operation.RETRY: lambda: InstallationService.retry(JOURNAL, 'a'),
            Operation.UNINSTALL: lambda: InstallationService.uninstall(JOURNAL, 'a'),
            Operation.INSTALL: lambda: self.install(),
        }
        states = [s for s in InstallationState if s not in TRANSIENT_STATES]
        for state in states:
            for operation, call in calls.items():
                with self.subTest(state=state, operation=operation):
                    PluginInstallation.objects.all().delete()
                    self.install()
                    PluginInstallation.objects.filter(plugin_id=JOURNAL).update(
                        state=state, target_state=InstallationState.ENABLED
                    )
                    allowed = state in TRANSITIONS[operation][0]
                    if allowed:
                        call()
                    else:
                        with self.assertRaises(TransitionError):
                            call()
        for state in TRANSIENT_STATES:
            with self.subTest(state=state):
                self.assertEqual(allowed_operations(state), [])
        self.assertEqual(allowed_operations(ABSENT), [Operation.INSTALL])


class FailureAndRecoveryTests(_Base):
    def _failing_publish(self, times: int = 1):
        real = type(self.point).publish
        calls = {'n': 0}

        def publish(point, text):
            calls['n'] += 1
            if calls['n'] <= times:
                raise OSError('disk full')
            return real(point, text)

        return patch.object(type(self.point), 'publish', publish)

    def test_a_failed_install_is_recorded_and_retry_completes_it(self) -> None:
        with self._failing_publish(times=2), self.assertRaisesMessage(PluginError, 'disk full'):
            self.install()
        row = self.row()
        self.assertEqual(row.state, InstallationState.FAILED)
        self.assertEqual(row.target_state, InstallationState.ENABLED)
        self.assertIn('disk full', row.last_error)
        self.assertTrue(AuditService.has('plugin_failed', severity='err'))
        self.assertEqual(self.bcc(), None)  # nothing was written
        InstallationService.retry(JOURNAL, 'a')
        self.assertEqual(self.row().state, InstallationState.ENABLED)
        self.assertEqual(self.bcc(), ADDR)

    def test_a_failed_plugin_contributes_nothing_and_can_be_uninstalled(self) -> None:
        self.install()
        with self._failing_publish(times=1), self.assertRaises(PluginError):
            InstallationService.configure(JOURNAL, {'archive_address': 'other@ifinmail.test'}, 'a')
        # The reconcile after the failure removed the failed plugin's value.
        self.assertEqual(self.bcc(), '')
        InstallationService.uninstall(JOURNAL, 'a')
        self.assertIsNone(self.row())

    def test_a_failed_uninstall_retries_into_removal(self) -> None:
        self.install()
        with self._failing_publish(times=2), self.assertRaises(PluginError):
            InstallationService.uninstall(JOURNAL, 'a')
        self.assertEqual(self.row().target_state, ABSENT)
        InstallationService.retry(JOURNAL, 'a')
        self.assertIsNone(self.row())
        self.assertEqual(self.bcc(), '')

    def test_an_operation_interrupted_mid_way_is_finished_later(self) -> None:
        self.install()
        old = timezone.now() - timedelta(seconds=STALE_SECONDS + 5)
        PluginInstallation.objects.filter(plugin_id=JOURNAL).update(
            state=InstallationState.APPLYING,
            target_state=InstallationState.DISABLED,
            pending_operation=Operation.DISABLE,
            updated_at=old,
        )
        row = InstallationService.get(JOURNAL)  # a page view finishes it
        self.assertEqual(row.state, InstallationState.DISABLED)
        self.assertEqual(self.bcc(), '')

    def test_reconcile_finishes_interrupted_installs_and_uninstalls(self) -> None:
        self.install()
        old = timezone.now() - timedelta(seconds=STALE_SECONDS + 5)
        PluginInstallation.objects.filter(plugin_id=JOURNAL).update(
            state=InstallationState.UNINSTALLING,
            target_state=ABSENT,
            pending_operation=Operation.UNINSTALL,
            updated_at=old,
        )
        self.assertEqual(InstallationService.reconcile()['finished_stale'], 1)
        self.assertIsNone(self.row())
        self.assertEqual(self.bcc(), '')

    def test_a_fresh_transient_row_is_left_alone(self) -> None:
        self.install()
        PluginInstallation.objects.filter(plugin_id=JOURNAL).update(
            state=InstallationState.APPLYING, target_state=InstallationState.ENABLED
        )
        self.assertEqual(InstallationService.reconcile()['finished_stale'], 0)
        self.assertEqual(self.row().state, InstallationState.APPLYING)


class ConflictTests(_Base):
    def test_two_plugins_cannot_set_the_same_value(self) -> None:
        self.publish_submission()  # test-journal also sets the journal address
        self.install()
        with self.assertRaisesMessage(
            ConflictError, 'compliance-journal already sets archive_address of mail.journal'
        ):
            InstallationService.install('test-journal', {'archive_address': ADDR}, 'a')
        self.assertFalse(PluginInstallation.objects.filter(plugin_id='test-journal').exists())
        InstallationService.disable(JOURNAL, 'a')
        InstallationService.install('test-journal', {'archive_address': 'other@ifinmail.test'}, 'a')
        with self.assertRaises(ConflictError):
            InstallationService.enable(JOURNAL, 'a')
        self.assertEqual(self.bcc(), 'other@ifinmail.test')


class UpdateAndRetirementTests(_Base):
    def test_update_carries_settings_over_and_takes_new_defaults(self) -> None:
        self.publish_submission()
        InstallationService.install('test-journal', {'archive_address': ADDR}, 'a')
        row = InstallationService.get('test-journal')
        self.assertFalse(
            InstallationService.update_available(row, CatalogService.get('test-journal'))
        )
        with self.assertRaises(TransitionError):
            InstallationService.update('test-journal', 'a')
        settings = [
            {'key': 'archive_address', 'type': 'mailbox', 'label': 'Archive', 'required': True},
            {'key': 'label', 'type': 'text', 'label': 'Label', 'default': 'journal'},
        ]
        self.publish_submission(plugin__version='1.1.0', settings=settings)
        row = InstallationService.get('test-journal')
        self.assertTrue(
            InstallationService.update_available(row, CatalogService.get('test-journal'))
        )
        InstallationService.update('test-journal', 'a', row.revision)
        row = InstallationService.get('test-journal')
        self.assertEqual(row.version, '1.1.0')
        self.assertEqual(row.settings, {'archive_address': ADDR, 'label': 'journal'})
        self.assertEqual(row.state, InstallationState.ENABLED)
        self.assertTrue(AuditService.has('plugin_update'))

    def test_update_with_a_new_required_setting_needs_a_value(self) -> None:
        self.publish_submission()
        InstallationService.install('test-journal', {'archive_address': ADDR}, 'a')
        settings = [
            {'key': 'archive_address', 'type': 'mailbox', 'label': 'Archive', 'required': True},
            {'key': 'owner', 'type': 'email', 'label': 'Owner', 'required': True},
        ]
        self.publish_submission(plugin__version='2.0.0', settings=settings)
        with self.assertRaises(SettingsError) as caught:
            InstallationService.update('test-journal', 'a')
        self.assertIn('owner', caught.exception.errors)
        self.assertEqual(InstallationService.get('test-journal').version, '1.0.0')
        InstallationService.update('test-journal', 'a', settings={'owner': 'o@ifinmail.test'})
        self.assertEqual(InstallationService.get('test-journal').version, '2.0.0')

    def test_a_retired_plugin_keeps_working_but_cannot_be_installed_again(self) -> None:
        sub_id = self.publish_submission()
        InstallationService.install('test-journal', {'archive_address': ADDR}, 'a')
        SubmissionService.retire(sub_id, 'admin@ifinmail.test')
        self.assertIsNone(CatalogService.get('test-journal'))
        InstallationService.publish_all()
        self.assertEqual(self.bcc(), ADDR)  # rendered from the stored manifest snapshot
        InstallationService.disable('test-journal', 'a')
        InstallationService.enable('test-journal', 'a')
        InstallationService.uninstall('test-journal', 'a')
        with self.assertRaises(NotFoundError):
            InstallationService.install('test-journal', {'archive_address': ADDR}, 'a')


class AppliedStatusTests(_Base):
    def ack(self, content: str) -> None:
        Path(self.status_dir, 'postfix-plugins.applied').write_text(content + '\n')

    def test_applied_applying_not_applied_and_unknown(self) -> None:
        self.assertEqual(self.point.applied_status(), ApplyStatus.UNKNOWN)  # no file yet
        self.install()
        self.assertEqual(self.point.applied_status(), ApplyStatus.UNKNOWN)  # no acknowledgement
        self.ack('0' * 64)
        self.assertEqual(self.point.applied_status(), ApplyStatus.APPLYING)  # just written
        path = Path(self.runtime_dir) / 'postfix-plugins.conf'
        old = time.time() - 600
        os.utime(path, (old, old))
        self.assertEqual(self.point.applied_status(), ApplyStatus.NOT_APPLIED)
        self.ack(hashlib.sha256(path.read_bytes()).hexdigest())
        self.assertEqual(self.point.applied_status(), ApplyStatus.APPLIED)
        self.assertEqual(InstallationService.apply_status()['postfix.main'], ApplyStatus.APPLIED)
