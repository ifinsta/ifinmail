"""Typed building blocks for the authoritative DNS server."""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import StrEnum


class ZoneMode(StrEnum):
    """Who answers DNS for a domain."""

    AUTHORITATIVE = 'authoritative'  # this server publishes the zone (Knot DNS)
    EXTERNAL = 'external'  # the registrar or a DNS provider hosts it


class RecordType(StrEnum):
    A = 'A'
    AAAA = 'AAAA'
    CNAME = 'CNAME'
    MX = 'MX'
    TXT = 'TXT'
    SRV = 'SRV'
    CAA = 'CAA'
    NS = 'NS'  # delegation of a sub-zone only; the apex NS set is managed


CUSTOM_TYPES: tuple[RecordType, ...] = tuple(RecordType)


@dataclass(frozen=True)
class ZoneRecord:
    """One resource record of a zone, as written to the zone file."""

    name: str  # '@' for the apex, otherwise relative to the zone ('www', '*.app')
    type: str
    value: str
    ttl: int = 3600
    priority: int | None = None  # MX, SRV
    managed: bool = True  # generated by ifinmail (cannot be edited as a custom record)
    record_id: str = ''  # set for custom records


@dataclass(frozen=True)
class DelegationStatus:
    """Is the world actually asking this server about the zone?"""

    zone: str
    serving: bool | None = None  # our DNS container answers authoritatively
    delegated: bool | None = None  # the parent zone's NS set names this server
    expected_ns: tuple[str, ...] = ()
    public_ns: tuple[str, ...] = ()
    ds_published: bool | None = None
    detail: str = ''


@dataclass(frozen=True)
class DSRecord:
    """A DNSSEC delegation-signer record to publish at the registrar."""

    key_tag: int
    algorithm: int
    digest_type: int
    digest: str

    def text(self) -> str:
        return f'{self.key_tag} {self.algorithm} {self.digest_type} {self.digest}'


@dataclass
class ZoneView:
    """Everything the zone page shows for one domain."""

    zone: str
    mode: ZoneMode
    records: list[ZoneRecord] = field(default_factory=list)
    ds: list[DSRecord] = field(default_factory=list)
    serial: int = 0
    delegation: DelegationStatus | None = None
