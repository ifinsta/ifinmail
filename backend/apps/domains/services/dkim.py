"""DKIM key management: one RSA key per domain, stored in the database and
written to the shared key directory that Rspamd signs from.

Rspamd is configured with ``path = "/etc/dkim/$domain.$selector.key"`` so a new
domain is signed as soon as its key file exists; no per-domain config edits.
"""

from __future__ import annotations

import base64
import logging
import os
import tempfile
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from django.db import transaction

from ..models import DKIMKey, Domain

logger = logging.getLogger('backend')

_KEY_BITS = 2048


def key_dir() -> Path:
    return Path(os.environ.get('DKIM_KEY_DIR', '/etc/dkim'))


def default_selector() -> str:
    return os.environ.get('DKIM_SELECTOR', 'default') or 'default'


class DKIMService:
    @staticmethod
    def key_path(domain_name: str, selector: str) -> Path:
        return key_dir() / f'{domain_name}.{selector}.key'

    @staticmethod
    def legacy_key_path(domain_name: str, selector: str) -> Path:
        """File name used by older provision.sh runs: ``<selector>.<domain>.key``."""
        return key_dir() / f'{selector}.{domain_name}.key'

    @staticmethod
    def public_txt_value(public_key_pem: str) -> str:
        """DNS TXT value (``v=DKIM1; k=rsa; p=...``) for a PEM public key."""
        public = serialization.load_pem_public_key(public_key_pem.encode())
        der = public.public_bytes(
            serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo
        )
        return 'v=DKIM1; k=rsa; p=' + base64.b64encode(der).decode()

    @staticmethod
    def get_active(domain: Domain, selector: str | None = None) -> DKIMKey | None:
        return DKIMKey.objects.filter(
            domain=domain, selector=selector or default_selector(), active=True
        ).first()

    @staticmethod
    def txt_value_for(domain_name: str, selector: str | None = None) -> str:
        """Published DKIM value for a domain, or '' if it has no key yet."""
        domain = Domain.objects.filter(name=domain_name).first()
        if domain is None:
            return ''
        key = DKIMService.get_active(domain, selector)
        return DKIMService.public_txt_value(key.public_key) if key else ''

    @staticmethod
    def _write_private_key(domain_name: str, selector: str, pem: str) -> Path:
        directory = key_dir()
        directory.mkdir(parents=True, exist_ok=True)
        target = DKIMService.key_path(domain_name, selector)
        fd, tmp = tempfile.mkstemp(dir=directory, prefix='.dkim.')
        try:
            with os.fdopen(fd, 'w', encoding='ascii') as handle:
                handle.write(pem)
            # Rspamd runs as another user in its own container and only mounts this
            # directory read-only, so the file must be group/world readable.
            os.chmod(tmp, 0o644)
            os.replace(tmp, target)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise
        return target

    @staticmethod
    def _import_legacy(domain: Domain, selector: str) -> DKIMKey | None:
        """Adopt a key generated by provision.sh so existing installs keep signing."""
        path = DKIMService.legacy_key_path(domain.name, selector)
        if not path.is_file():
            return None
        try:
            private_pem = path.read_text(encoding='ascii')
            private = serialization.load_pem_private_key(private_pem.encode(), password=None)
        except (OSError, ValueError, TypeError):
            logger.warning('Ignoring unreadable legacy DKIM key %s', path)
            return None
        public_pem = (
            private.public_key()
            .public_bytes(
                serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo
            )
            .decode()
        )
        return DKIMKey.objects.create(
            domain=domain, selector=selector, private_key=private_pem, public_key=public_pem
        )

    @staticmethod
    def generate(domain: Domain, selector: str | None = None) -> DKIMKey:
        """Create a fresh key (replacing any existing one for this selector)."""
        selector = selector or default_selector()
        private = rsa.generate_private_key(public_exponent=65537, key_size=_KEY_BITS)
        private_pem = private.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.TraditionalOpenSSL,
            serialization.NoEncryption(),
        ).decode()
        public_pem = (
            private.public_key()
            .public_bytes(
                serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo
            )
            .decode()
        )
        with transaction.atomic():
            DKIMKey.objects.filter(domain=domain, selector=selector).delete()
            key = DKIMKey.objects.create(
                domain=domain, selector=selector, private_key=private_pem, public_key=public_pem
            )
        DKIMService._write_private_key(domain.name, selector, private_pem)
        return key

    @staticmethod
    def ensure(domain: Domain, selector: str | None = None) -> tuple[DKIMKey, bool]:
        """Make sure the domain has a key in the database and on disk.

        Returns ``(key, created)``. Idempotent: an existing key is only re-written
        to disk if its file is missing.
        """
        selector = selector or default_selector()
        key = DKIMService.get_active(domain, selector)
        created = False
        if key is None:
            key = DKIMService._import_legacy(domain, selector)
            if key is None:
                return DKIMService.generate(domain, selector), True
            created = True
        if not DKIMService.key_path(domain.name, selector).is_file():
            DKIMService._write_private_key(domain.name, selector, key.private_key)
        return key, created

    @staticmethod
    def sync_files() -> int:
        """Write every active key to disk (used by the periodic job). Returns count written."""
        written = 0
        for key in DKIMKey.objects.filter(active=True).select_related('domain'):
            if not DKIMService.key_path(key.domain.name, key.selector).is_file():
                DKIMService._write_private_key(key.domain.name, key.selector, key.private_key)
                written += 1
        return written
