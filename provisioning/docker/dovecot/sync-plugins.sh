#!/usr/bin/env bash
# Applies plugin settings for Dovecot (extension point dovecot.policy).
#
# The console writes <runtime>/dovecot-plugins.conf ("key = value" lines). When it changes this
# script re-validates every key and value, renders $OUT (included with !include_try at the end of
# dovecot.conf), checks the whole configuration with `doveconf -n`, and only then reloads Dovecot.
# A configuration that fails the check is rolled back and not acknowledged. The SHA-256 of an
# applied file is written to <status>/dovecot-plugins.applied.
#
#   sync-plugins.sh          watch forever (every 10 s)
#   sync-plugins.sh --once   apply once and exit (start-up and tests)
set -u

FILE="${IFINMAIL_DOVECOT_PLUGINS_FILE:-/var/lib/ifinmail/runtime/dovecot-plugins.conf}"
STATE="${IFINMAIL_DOVECOT_PLUGINS_STATE:-/var/run/ifinmail-dovecot-plugins.sha256}"
STATUS_DIR="${IFINMAIL_STATUS_DIR:-/var/lib/ifinmail/status}"
OUT="${IFINMAIL_DOVECOT_OUT:-/etc/dovecot/ifinmail-plugins.conf}"
DOVECONF="${DOVECONF_BIN:-doveconf}"
RELOAD="${DOVECOT_RELOAD:-doveadm reload}"
INTERVAL="${IFINMAIL_SYNC_INTERVAL:-10}"
CERT_FILE="${IFINMAIL_CERT_FILE:-/etc/dovecot/certs/fullchain.pem}"
CERT_SEEN=''

log() { echo "ifinmail-dovecot-sync: $*"; }

DAYS='^([1-9][0-9]{0,3})?$'
declare -A RULES=(
    [max_redirects]='^([0-9]|1[0-9]|20)?$'
    [autoexpunge_trash_days]="$DAYS"
    [autoexpunge_junk_days]="$DAYS"
    [autoexpunge_sent_days]="$DAYS"
    [quota_warnings]='^(yes|no)?$'
)
declare -A FOLDERS=(
    [autoexpunge_trash_days]=Trash
    [autoexpunge_junk_days]=Junk
    [autoexpunge_sent_days]=Sent
)

render() {
    local key days body=''
    for key in autoexpunge_trash_days autoexpunge_junk_days autoexpunge_sent_days; do
        days="${VALUES[$key]:-}"
        [ -n "$days" ] || continue
        body+="  mailbox ${FOLDERS[$key]} {"$'\n'"    autoexpunge = ${days}d"$'\n'"  }"$'\n'
    done
    echo '# Generated by ifinmail from enabled plugins (dovecot.policy). Do not edit.'
    [ -n "$body" ] && printf 'namespace inbox {\n%s}\n' "$body"
    if [ -n "${VALUES[max_redirects]:-}" ]; then
        printf 'plugin {\n  sieve_max_redirects = %s\n}\n' "${VALUES[max_redirects]}"
    fi
    if [ "${VALUES[quota_warnings]:-}" = "yes" ]; then
        cat <<'EOF'
plugin {
  quota_warning = storage=95%% quota-warning 95 %u
  quota_warning2 = storage=80%% quota-warning 80 %u
}
service quota-warning {
  executable = script /usr/local/bin/ifinmail-quota-warning
  user = vmail
  unix_listener quota-warning {
    user = vmail
    mode = 0600
  }
}
EOF
    fi
}

apply_once() {
    [ -r "$FILE" ] || return 0
    local current previous=""
    current="$(sha256sum "$FILE" | cut -d' ' -f1)"
    [ -r "$STATE" ] && previous="$(cat "$STATE")"
    if [ "$current" != "$previous" ]; then
        declare -gA VALUES=()
        local line key value
        while IFS= read -r line || [ -n "$line" ]; do
            [[ "$line" =~ ^[[:space:]]*$ || "$line" =~ ^[[:space:]]*# ]] && continue
            if [[ ! "$line" =~ ^([a-z_]+)[[:space:]]*=[[:space:]]*(.*)$ ]]; then
                log "ignoring malformed line"; continue
            fi
            key="${BASH_REMATCH[1]}"; value="${BASH_REMATCH[2]}"
            if [ -z "${RULES[$key]+set}" ]; then log "ignoring key not on the allow-list: $key"; continue; fi
            if [[ ! "$value" =~ ${RULES[$key]} ]]; then log "ignoring unsafe value for $key"; continue; fi
            if [[ "$key" == autoexpunge_* && -n "$value" && "$value" -gt 3650 ]]; then
                log "ignoring out-of-range value for $key"; continue
            fi
            VALUES[$key]="$value"
        done < "$FILE"

        local previous_conf=''
        [ -r "$OUT" ] && previous_conf="$(cat "$OUT")"
        render > "$OUT.tmp" && mv "$OUT.tmp" "$OUT"
        chmod 644 "$OUT"
        if ! "$DOVECONF" -n >/dev/null 2>&1; then
            log "configuration check failed; keeping the previous settings"
            printf '%s\n' "$previous_conf" > "$OUT"
            return 1
        fi
        if ! $RELOAD >/dev/null 2>&1; then
            log "reload failed; will retry (not acknowledged)"
            return 1
        fi
        echo "$current" > "$STATE"
        log "applied $(basename "$FILE")"
    fi
    acknowledge
}

acknowledge() {
    [ -r "$STATE" ] && [ -d "$STATUS_DIR" ] && [ -w "$STATUS_DIR" ] || return 0
    local applied
    applied="$(cat "$STATE")"
    [ "$(cat "$STATUS_DIR/dovecot-plugins.applied" 2>/dev/null)" = "$applied" ] && return 0
    printf '%s\n' "$applied" > "$STATUS_DIR/dovecot-plugins.applied.tmp" \
        && mv "$STATUS_DIR/dovecot-plugins.applied.tmp" "$STATUS_DIR/dovecot-plugins.applied"
    chmod 644 "$STATUS_DIR/dovecot-plugins.applied" 2>/dev/null || true
}

if [ "${1:-}" = "--once" ]; then
    apply_once
    exit 0
fi

# A renewed certificate (certbot writes a new file behind the live/ symlink) takes effect on reload.
watch_certificate() {
    local now
    now="$(cksum < "$CERT_FILE" 2>/dev/null)" || return 0
    if [ -n "$CERT_SEEN" ] && [ "$now" != "$CERT_SEEN" ]; then
        $RELOAD >/dev/null 2>&1 || return 0
        log "certificate changed; reloaded"
    fi
    CERT_SEEN="$now"
}

while :; do
    apply_once
    watch_certificate
    sleep "$INTERVAL"
done
