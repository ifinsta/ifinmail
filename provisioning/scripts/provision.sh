#!/usr/bin/env bash
# ifinmail provision.sh - one-command production provisioning.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROVISIONING_DIR="$(dirname "$SCRIPT_DIR")"
DOCKER_DIR="$PROVISIONING_DIR/docker"
ENV_FILE="$PROVISIONING_DIR/.env"
DOMAIN="${DOMAIN:?DOMAIN must be set}"
MAIL_DOMAIN="${MAIL_DOMAIN:-$DOMAIN}"
MAIL_HOSTNAME="${MAIL_HOSTNAME:-mail.$DOMAIN}"
ADMIN_EMAIL="${ADMIN_EMAIL:-admin@$DOMAIN}"
DKIM_SELECTOR="${DKIM_SELECTOR:-default}"
COMPOSE=()
LEGACY_COMPOSE=false

die() {
    echo "ERROR: $*" >&2
    exit 1
}

need_cmd() {
    command -v "$1" >/dev/null 2>&1 || die "$1 is required"
}

normalize_vars() {
    # Normalize domain to lowercase
    DOMAIN="$(echo "$DOMAIN" | tr '[:upper:]' '[:lower:]')"
    # Strip trailing dot (FQDN notation)
    DOMAIN="${DOMAIN%.}"
    MAIL_DOMAIN="$(echo "$MAIL_DOMAIN" | tr '[:upper:]' '[:lower:]')"
    MAIL_DOMAIN="${MAIL_DOMAIN%.}"
    # Validate DKIM_SELECTOR: only lowercase letters, digits, hyphens
    if ! echo "$DKIM_SELECTOR" | grep -qE '^[a-z0-9]([a-z0-9-]*[a-z0-9])?$'; then
        echo "WARNING: DKIM_SELECTOR '$DKIM_SELECTOR' is not a valid DNS label. Using 'default'."
        DKIM_SELECTOR="default"
    fi
}

detect_compose() {
    if docker compose version >/dev/null 2>&1; then
        COMPOSE=(docker compose --env-file "$ENV_FILE" -f "$DOCKER_DIR/docker-compose.yml")
    elif command -v docker-compose >/dev/null 2>&1; then
        COMPOSE=(docker-compose --env-file "$ENV_FILE" -f "$DOCKER_DIR/docker-compose.yml")
        LEGACY_COMPOSE=true
    else
        die "docker compose v2 or docker-compose v1 is required"
    fi
}

rand_b64() {
    openssl rand -base64 "$1" | tr -d '\n'
}

rand_urlsafe() {
    openssl rand -base64 "$1" | tr '+/' '-_' | tr -d '=\n'
}

detect_public_ip() {
    # Public IPv4 of this server (used for the DNS zone and for the nameserver glue records).
    local ip=""
    ip="$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || true)"
    if ! [[ "$ip" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
        ip="$(ip -4 route get 1.1.1.1 2>/dev/null | grep -oP 'src \K\S+' | head -1 || true)"
    fi
    echo "$ip"
}

ensure_env() {
    if [ -f "$ENV_FILE" ]; then
        # Strip Windows CRLF line endings if present
        sed -i 's/\r$//' "$ENV_FILE" 2>/dev/null || true
        set -a
        # shellcheck disable=SC1090
        source "$ENV_FILE"
        set +a

        DOMAIN="${DOMAIN:?DOMAIN must be set}"
        MAIL_DOMAIN="${MAIL_DOMAIN:-$DOMAIN}"
        MAIL_HOSTNAME="${MAIL_HOSTNAME:-mail.$DOMAIN}"
        ADMIN_EMAIL="${ADMIN_EMAIL:-admin@$DOMAIN}"
        DKIM_SELECTOR="${DKIM_SELECTOR:-default}"

        grep -q '^MAIL_DOMAIN=' "$ENV_FILE" || echo "MAIL_DOMAIN=$MAIL_DOMAIN" >> "$ENV_FILE"
        grep -q '^MAIL_HOSTNAME=' "$ENV_FILE" || echo "MAIL_HOSTNAME=$MAIL_HOSTNAME" >> "$ENV_FILE"
        grep -q '^ADMIN_EMAIL=' "$ENV_FILE" || echo "ADMIN_EMAIL=$ADMIN_EMAIL" >> "$ENV_FILE"
        grep -q '^DKIM_SELECTOR=' "$ENV_FILE" || echo "DKIM_SELECTOR=$DKIM_SELECTOR" >> "$ENV_FILE"
        grep -q '^BACKUP_GPG_PASSPHRASE=' "$ENV_FILE" || echo "BACKUP_GPG_PASSPHRASE=$(rand_b64 32)" >> "$ENV_FILE"
        grep -q '^RSPAMD_CONTROLLER_PASSWORD=' "$ENV_FILE" || echo "RSPAMD_CONTROLLER_PASSWORD=$(rand_b64 24)" >> "$ENV_FILE"
        grep -q '^SERVER_IP=' "$ENV_FILE" || echo "SERVER_IP=$(detect_public_ip)" >> "$ENV_FILE"
        grep -q '^DNS_NS_HOSTS=' "$ENV_FILE" || echo "DNS_NS_HOSTS=ns1.$MAIL_HOSTNAME,ns2.$MAIL_HOSTNAME" >> "$ENV_FILE"
        normalize_vars
        return
    fi

    umask 077
    cat > "$ENV_FILE" <<EOF
# Generated by provisioning/scripts/provision.sh
DOMAIN=$DOMAIN
MAIL_DOMAIN=$MAIL_DOMAIN
MAIL_HOSTNAME=$MAIL_HOSTNAME
ADMIN_EMAIL=$ADMIN_EMAIL

COREDNS_IP=127.0.0.1

POSTGRES_ADMIN_PASSWORD=$(rand_b64 36)
APP_DB_PASSWORD=$(rand_urlsafe 24)
DOVECOT_DB_PASSWORD=$(rand_b64 36)
POSTFIX_DB_PASSWORD=$(rand_b64 36)

SECRET_KEY=$(rand_b64 48)
DJANGO_ALLOWED_HOSTS=$DOMAIN,$MAIL_HOSTNAME,api,localhost,127.0.0.1

REDIS_HOST=redis
REDIS_PORT=6379
REDIS_PASSWORD=$(rand_urlsafe 24)

RSPAMD_CONTROLLER_PASSWORD=$(rand_b64 24)

DKIM_SELECTOR=$DKIM_SELECTOR

# Authoritative DNS: this server's public address and the nameserver names it answers as.
SERVER_IP=$(detect_public_ip)
DNS_NS_HOSTS=ns1.$MAIL_HOSTNAME,ns2.$MAIL_HOSTNAME
# DNS_BIND_IP=       # set to the server IP if another service (systemd-resolved) holds port 53

BACKUP_RETENTION_DAYS=30
BACKUP_ENCRYPT=true
BACKUP_GPG_RECIPIENT=${BACKUP_GPG_RECIPIENT:-ifinmail-backup@$DOMAIN}
BACKUP_GPG_PASSPHRASE=$(rand_b64 32)

MONITOR_QUEUE_WARN=50
MONITOR_QUEUE_CRITICAL=200
MONITOR_CERT_WARN_DAYS=30
MONITOR_CERT_CRITICAL_DAYS=7

DJANGO_SUPERUSER_EMAIL=$ADMIN_EMAIL
DJANGO_SUPERUSER_USERNAME=admin
DJANGO_SUPERUSER_PASSWORD=$(rand_b64 16)
EOF

    echo "Created production environment: $ENV_FILE"
}

validate_env() {
    local required=(
        DOMAIN
        MAIL_DOMAIN
        MAIL_HOSTNAME
        ADMIN_EMAIL
        POSTGRES_ADMIN_PASSWORD
        DOVECOT_DB_PASSWORD
        POSTFIX_DB_PASSWORD
        SECRET_KEY
        DJANGO_SUPERUSER_PASSWORD
        APP_DB_PASSWORD
    )
    local missing=false

    for name in "${required[@]}"; do
        local value="${!name:-}"
        if [ -z "$value" ] || [[ "$value" == change_me* ]] || [[ "$value" == dev_* ]] || [[ "$value" == *example.com* ]]; then
            echo "  $name is missing or still uses a placeholder"
            missing=true
        fi
    done

    [ "$missing" = false ] || die "update $ENV_FILE and rerun make provision"
}

ensure_directories() {
    mkdir -p "$DOCKER_DIR/certs/live/$MAIL_HOSTNAME" "$DOCKER_DIR/nginx/www" "$DOCKER_DIR/dkim"
}

ensure_bootstrap_cert() {
    local cert_dir="$DOCKER_DIR/certs/live/$MAIL_HOSTNAME"
    local cert="$cert_dir/fullchain.pem"
    local key="$cert_dir/privkey.pem"
    local dh="$cert_dir/dh.pem"

    mkdir -p "$cert_dir"

    if [ ! -s "$cert" ] || [ ! -s "$key" ]; then
        echo "Creating bootstrap self-signed TLS certificate for $MAIL_HOSTNAME..."
        openssl req -x509 -nodes -newkey rsa:2048 -days 30 \
            -subj "/CN=$MAIL_HOSTNAME" \
            -addext "subjectAltName=DNS:$DOMAIN,DNS:$MAIL_HOSTNAME" \
            -keyout "$key" \
            -out "$cert" >/dev/null 2>&1
        chmod 600 "$key"
    fi

    if [ ! -s "$dh" ]; then
        echo "Generating Dovecot DH parameters..."
        openssl dhparam -out "$dh" 2048 >/dev/null 2>&1
    fi
}

ensure_mta_sts() {
    # The policy is rendered by the api for every hosted domain (https://mta-sts.<domain>/
    # .well-known/mta-sts.txt). It starts in "testing" mode; switch to "enforce" with
    # MTA_STS_MODE after TLS delivery has been verified for a couple of weeks.
    echo "MTA-STS: policy is served by the console in testing mode (set MTA_STS_MODE=enforce later)."
}

ensure_dkim() {
    local key_path="$DOCKER_DIR/dkim/$DKIM_SELECTOR.$DOMAIN.key"
    local pub_path="${key_path%.key}.pub"

    if [ ! -s "$key_path" ]; then
        echo "Generating DKIM key for $DKIM_SELECTOR._domainkey.$DOMAIN..."
        openssl genrsa -out "$key_path" 2048 >/dev/null 2>&1
        openssl rsa -in "$key_path" -pubout -out "$pub_path" >/dev/null 2>&1
    fi

    # The api (uid 1000) creates and reads per-domain keys here; Rspamd mounts the
    # directory read-only and runs as another user, so key files must be readable.
    chown -R 1000:1000 "$DOCKER_DIR/dkim"
    chmod 755 "$DOCKER_DIR/dkim"
    find "$DOCKER_DIR/dkim" -type f -exec chmod 644 {} +

    # Rspamd signs every domain from /etc/dkim/<domain>.<selector>.key (generic config in
    # rspamd/local.d/dkim_signing.conf); the console adopts this key and creates others.
}

ensure_backup_gpg_key() {
    local gpg_key_id="${BACKUP_GPG_RECIPIENT:-ifinmail-backup@$DOMAIN}"
    local gpg_pass="${BACKUP_GPG_PASSPHRASE:-}"

    if gpg --list-keys "$gpg_key_id" >/dev/null 2>&1; then
        echo "GPG backup key already exists: $gpg_key_id"
        return
    fi

    if [ -z "$gpg_pass" ]; then
        echo "WARNING: BACKUP_GPG_PASSPHRASE not set. Generating passphrase..."
        gpg_pass="$(rand_b64 32)"
        echo "BACKUP_GPG_PASSPHRASE=$gpg_pass" >> "$ENV_FILE"
    fi

    echo "Generating GPG backup key ($gpg_key_id)..."
    cat > /tmp/gpg-batch.txt << GPGBATCH
%echo Generating ifinmail backup GPG key
Key-Type: RSA
Key-Length: 4096
Key-Usage: encrypt
Name-Real: ifinmail Backup
Name-Email: $gpg_key_id
Expire-Date: 0
Passphrase: $gpg_pass
%commit
%echo Done
GPGBATCH

    gpg --batch --pinentry-mode=loopback --passphrase "$gpg_pass" --gen-key /tmp/gpg-batch.txt 2>/dev/null
    rm -f /tmp/gpg-batch.txt

    if gpg --list-keys "$gpg_key_id" >/dev/null 2>&1; then
        local fp
        fp="$(gpg --fingerprint "$gpg_key_id" 2>/dev/null | head -2 | tail -1 | tr -d ' ')"
        echo "GPG backup key generated successfully (fingerprint: $fp)"
    else
        echo "WARNING: Failed to generate GPG backup key. Backup encryption disabled."
    fi
}

obtain_certificate() {
    local live_dir="$DOCKER_DIR/certs/live/$MAIL_HOSTNAME"
    local issuer

    issuer="$(openssl x509 -in "$live_dir/fullchain.pem" -noout -issuer 2>/dev/null || true)"
    if [[ "$issuer" != *"Let's Encrypt"* ]]; then
        echo "Attempting Let's Encrypt certificate for $DOMAIN and $MAIL_HOSTNAME..."
        if "$SCRIPT_DIR/obtain-ssl.sh"; then
            return
        fi

        echo "WARNING: Let's Encrypt issuance failed. The stack is running with a temporary self-signed certificate."
        echo "         Fix DNS/firewall for $DOMAIN and $MAIL_HOSTNAME, then rerun: make provision"
        ensure_bootstrap_cert
    else
        echo "Let's Encrypt certificate already present."
    fi
}

print_dns() {
    local pub_path="$DOCKER_DIR/dkim/$DKIM_SELECTOR.$DOMAIN.pub"
    local dkim_value
    dkim_value="$(grep -v '^-' "$pub_path" | tr -d '\n')"

    # Split DKIM public key into 255-char chunks for DNS TXT record compliance.
    # First chunk includes the prefix, subsequent chunks are pure key material.
    local prefix="v=DKIM1; k=rsa; p="
    local prefix_len=${#prefix}
    local chunk_size=$((255 - prefix_len))
    local dkim_chunks=""
    local remaining="$dkim_value"
    local first=true
    while [ -n "$remaining" ]; do
        if $first; then
            dkim_chunks="${dkim_chunks}\"${prefix}${remaining:0:$chunk_size}\""
            remaining="${remaining:$chunk_size}"
            first=false
        else
            dkim_chunks="${dkim_chunks} \"${remaining:0:255}\""
            remaining="${remaining:255}"
        fi
    done

    cat <<EOF

ifinmail is provisioned for $DOMAIN.

DNS records to publish:
  A      $DOMAIN                  <this server IPv4>
  A      $MAIL_HOSTNAME           <this server IPv4>
  MX     $DOMAIN                  10 $MAIL_HOSTNAME.
  TXT    $DOMAIN                  "v=spf1 mx ~all"
  TXT    _dmarc.$DOMAIN           "v=DMARC1; p=${DMARC_POLICY:-quarantine}; rua=mailto:postmaster@$DOMAIN"
  TXT    $DKIM_SELECTOR._domainkey.$DOMAIN $dkim_chunks
  TXT    _mta-sts.$DOMAIN          "v=STSv1; id=$(sha256sum "$DOCKER_DIR/nginx/www/.well-known/mta-sts.json" 2>/dev/null | cut -d' ' -f1 | head -c 16 || date +%Y%m%dT%H%M%SZ)"
  A      mta-sts.$DOMAIN           <this server IPv4>
  PTR    <this server IPv4>       $MAIL_HOSTNAME   (set at your VPS provider — not DNS host)
  AAAA   $DOMAIN                  <this server IPv6>  (if available)
  AAAA   $MAIL_HOSTNAME           <this server IPv6>  (if available)

Authoritative DNS (this server answers for $DOMAIN itself):
  Set the nameservers of $DOMAIN at your registrar to:
      ${DNS_NS_HOSTS:-ns1.$MAIL_HOSTNAME,ns2.$MAIL_HOSTNAME}
  The registrar also needs "glue" for them, because they live inside the zone:
      ns1.$MAIL_HOSTNAME  ->  ${SERVER_IP:-<this server IPv4>}
      ns2.$MAIL_HOSTNAME  ->  ${SERVER_IP:-<this server IPv4>}
  Then open the console (Settings > DNS server) to see the DNSSEC DS record to add at the
  registrar. The records above are published by this server; you only add them by hand if you
  keep DNS at another provider (switch the domain to "External DNS" in the console).

Reverse DNS (PTR) is critical for mail deliverability. Without it, many
providers (Gmail, Outlook) will reject or spam-folder your messages.
Set reverse DNS for your server's IPv4 address to point to $MAIL_HOSTNAME
through your VPS provider's control panel — not your DNS host.

After DNS is configured, verify with:
  dig +short MX $DOMAIN
  dig +short -x <your-server-ip>
  dig +short TXT $DKIM_SELECTOR._domainkey.$DOMAIN

Useful commands:
  make ps
  make logs
  make down
EOF
}

ensure_db_grants() {
    # init-db.sh only runs when the database is first created; apply newer grants too.
    echo "Applying database grants..."
    (cd "$DOCKER_DIR" && "${COMPOSE[@]}" exec -T postgres sh -c \
        'psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB"' < "$DOCKER_DIR/db-upgrade.sql" >/dev/null) \
        || echo "WARNING: could not apply db-upgrade.sql; run 'make provision' again once postgres is healthy."
}

ensure_backup_schedule() {
    # Daily encrypted backup via cron; the console shows when it last succeeded.
    local cron_file="/etc/cron.d/ifinmail-backup"
    local repo_root
    repo_root="$(cd "$PROVISIONING_DIR/.." && pwd)"
    if [ ! -d /etc/cron.d ] || [ ! -w /etc/cron.d ]; then
        echo "WARNING: /etc/cron.d is not writable; schedule 'make backup' yourself (daily)."
        return 0
    fi
    cat > "$cron_file" <<CRON
# Installed by ifinmail provision.sh. Runs a full backup every day.
SHELL=/bin/bash
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
15 3 * * * root cd $repo_root && set -a && . provisioning/.env && set +a && BACKUP_ENCRYPT=true make backup >> /var/log/ifinmail-backup.log 2>&1
CRON
    chmod 644 "$cron_file"
    echo "Daily backup scheduled in $cron_file (03:15)."
}

ensure_unattended_upgrades() {
    # Automatic OS security updates (Debian/Ubuntu). Container images are updated with `make reload`.
    if ! command -v apt-get >/dev/null 2>&1 || [ "$(id -u)" != "0" ]; then
        echo "Skipping unattended-upgrades (not a root Debian/Ubuntu host)."
        return 0
    fi
    if ! dpkg -s unattended-upgrades >/dev/null 2>&1; then
        DEBIAN_FRONTEND=noninteractive apt-get install -y -qq unattended-upgrades >/dev/null 2>&1 \
            || { echo "WARNING: could not install unattended-upgrades"; return 0; }
    fi
    cat > /etc/apt/apt.conf.d/20auto-upgrades <<APT
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
APT
    echo "Automatic OS security updates enabled."
}

preflight_checks() {
    echo "Running pre-flight checks..."

    # Check available disk space (need ~2GB for images + data)
    local available_kb
    available_kb="$(df "$PROVISIONING_DIR" | awk 'NR==2 {print $4}')"
    if [ "${available_kb:-0}" -lt 2097152 ]; then
        echo "WARNING: Less than 2GB disk space available. Builds may fail."
    fi

    # Check available RAM (need ~1GB for building and running)
    if [ -f /proc/meminfo ]; then
        local mem_avail_kb
        mem_avail_kb="$(awk '/MemAvailable/ {print $2}' /proc/meminfo)"
        if [ "${mem_avail_kb:-0}" -lt 1048576 ]; then
            echo "WARNING: Less than 1GB RAM available. Services may be OOM-killed."
        fi
    fi

    # Check if Docker daemon is running
    if ! docker info >/dev/null 2>&1; then
        die "Docker daemon is not running. Start it with: systemctl start docker"
    fi

    # Check if required ports are already in use
    for port in 25 80 143 443 465 587 993; do
        if ss -tlnp 2>/dev/null | grep -q ":${port} "; then
            echo "WARNING: Port $port is already in use. The stack may fail to bind."
        fi
    done

    # DNS (port 53): systemd-resolved's stub listens on 127.0.0.53, which blocks a wildcard bind.
    # Binding the DNS container to the public address alone avoids the clash.
    if ss -lnup 2>/dev/null | grep -qE '(^|[ *])(0\.0\.0\.0|\*|\[::\]):53 '; then
        echo "WARNING: Something else already answers DNS on port 53; the DNS server cannot start."
        echo "         Stop it, or set DNS_SERVER_ENABLED=0 in $ENV_FILE to keep DNS elsewhere."
    elif ss -lnup 2>/dev/null | grep -q '127\.0\.0\.53:53' && [ -z "${DNS_BIND_IP:-}" ]; then
        if [ -n "${SERVER_IP:-}" ]; then
            echo "systemd-resolved holds 127.0.0.53:53; binding the DNS server to $SERVER_IP only."
            echo "DNS_BIND_IP=$SERVER_IP" >> "$ENV_FILE"
            DNS_BIND_IP="$SERVER_IP"
        fi
    fi

    echo "Pre-flight checks complete."
}

ensure_kernel_settings() {
    if [ -r /proc/sys/vm/overcommit_memory ] && [ "$(cat /proc/sys/vm/overcommit_memory)" != "1" ]; then
        echo "Enabling vm.overcommit_memory=1 for Redis background saves..."
        sysctl -w vm.overcommit_memory=1 >/dev/null 2>&1 || \
            echo "WARNING: Could not set vm.overcommit_memory=1; Redis may warn during startup."
    fi

    if [ -d /etc/sysctl.d ] && [ -w /etc/sysctl.d ]; then
        cat > /etc/sysctl.d/99-ifinmail.conf <<EOF
vm.overcommit_memory = 1
EOF
    fi
}

main() {
    echo "======================================"
    echo "  ifinmail production provisioning"
    echo "======================================"

    need_cmd docker
    need_cmd openssl
    need_cmd gpg
    detect_compose

    ensure_env
    set -a
    # shellcheck disable=SC1090
    source "$ENV_FILE"
    set +a
    DOMAIN="${DOMAIN:?DOMAIN must be set}"
    MAIL_DOMAIN="${MAIL_DOMAIN:-$DOMAIN}"
    MAIL_HOSTNAME="${MAIL_HOSTNAME:-mail.$DOMAIN}"
    ADMIN_EMAIL="${ADMIN_EMAIL:-admin@$DOMAIN}"
    DKIM_SELECTOR="${DKIM_SELECTOR:-default}"
    normalize_vars
    validate_env
    preflight_checks
    ensure_kernel_settings
    ensure_directories
    ensure_bootstrap_cert
    ensure_mta_sts
    ensure_dkim
    ensure_backup_gpg_key
    ensure_backup_schedule
    ensure_unattended_upgrades

    echo "Building images..."
    (cd "$DOCKER_DIR" && "${COMPOSE[@]}" build --pull)

    if [ "$LEGACY_COMPOSE" = true ]; then
        (cd "$DOCKER_DIR" && "${COMPOSE[@]}" rm -fs api postfix dovecot rspamd >/dev/null 2>&1 || true)
    fi

    echo "Starting stack..."
    (cd "$DOCKER_DIR" && "${COMPOSE[@]}" up -d)

    obtain_certificate
    (cd "$DOCKER_DIR" && "${COMPOSE[@]}" restart postfix dovecot nginx)

    ensure_db_grants

    echo "Current service status:"
    (cd "$DOCKER_DIR" && "${COMPOSE[@]}" ps)

    print_dns
}

main "$@"
